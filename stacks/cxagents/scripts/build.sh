#!/usr/bin/env bash
# stacks/cxagents/scripts/build.sh — run the forwarder's tests in the pinned
# builder, build tailnet-forwarder:local, write stacks/cxagents/build.lock.
# Exit: 0 ok; 1 precondition; 3 test/build failure (build.lock unchanged).
#
# Toolchain pin: the digest-pinned builder image plus GOTOOLCHAIN=local (set in
# the Dockerfile's build stage). go.mod deliberately has NO `toolchain` line:
# a toolchain line breaks -mod=readonly builds, so the toolchain recorded in
# build.lock is read from the builder itself (`go version`).
set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
stack_dir="$(cd "${SCRIPT_DIR}/.." && pwd)"
src="${stack_dir}/forwarder"
ctx=colima-agents
img=tailnet-forwarder:local
lock="${stack_dir}/build.lock"

docker --context "$ctx" info >/dev/null 2>&1 || { echo "build: agents VM not running (dotfiles stacks vm-agents-up)" >&2; exit 1; }
builder="$(sed -n 's/^FROM \(golang:[^ ]*\) AS build$/\1/p' "${src}/Dockerfile")"
runtime="$(sed -n 's/^FROM \(gcr\.io\/distroless\/[^ ]*\)$/\1/p' "${src}/Dockerfile")"
case "$builder$runtime" in *@sha256:*@sha256:*) ;; *) echo "build: base images must be pinned by digest" >&2; exit 1 ;; esac
awk '/^FROM /{stage=$0} stage ~ /AS build$/ && /^ENV/ && /GOTOOLCHAIN=local/{found=1} END{exit !found}' "${src}/Dockerfile" \
    || { echo "build: the Dockerfile build stage must set GOTOOLCHAIN=local (the toolchain pin)" >&2; exit 1; }
if grep -q '^toolchain[[:space:]]' "${src}/go.mod"; then
    echo "build: go.mod has a toolchain line; remove it (it breaks -mod=readonly builds; the pin is the builder image + GOTOOLCHAIN=local)" >&2
    exit 1
fi

toolchain="$(docker --context "$ctx" run --rm --network none --entrypoint go "$builder" version \
    | awk '{for (i = 1; i <= NF; i++) if ($i ~ /^go[0-9]+\.[0-9]+(\.[0-9]+)?$/) {print $i; exit}}')"
[ -n "$toolchain" ] || { echo "build: cannot read the builder's Go toolchain version" >&2; exit 1; }

nocache=(); [ "${1:-}" = --no-cache ] && nocache=(--no-cache)
"${SCRIPT_DIR}/race-test.sh" || { echo "build: race tests failed (build.lock unchanged)" >&2; exit 3; }
docker --context "$ctx" build ${nocache[@]+"${nocache[@]}"} --target test "$src" || exit 3
docker --context "$ctx" build ${nocache[@]+"${nocache[@]}"} -t "$img" "$src" || exit 3

tmp="$(mktemp -d "$(getconf DARWIN_USER_TEMP_DIR)cxagents-build.XXXXXX")"
trap 'rm -rf "$tmp"; docker --context "$ctx" rm -f cxagents-build-extract >/dev/null 2>&1 || true' EXIT
# The image is built by here, so a failure to extract it is a build failure (3), not a precondition (1).
docker --context "$ctx" create --name cxagents-build-extract "$img" >/dev/null || exit 3
docker --context "$ctx" cp cxagents-build-extract:/tailnet-forwarder "$tmp/tailnet-forwarder" || exit 3
bin_sha="$(shasum -a 256 "$tmp/tailnet-forwarder" | cut -d' ' -f1)"
# go.mod after tidy: either `require tailscale.com vX` (one line) or inside a require block.
ts_ver="$(awk '$1=="require" && $2=="tailscale.com" {print $3; exit} $1=="tailscale.com" {print $2; exit}' "${src}/go.mod")"
[ -n "$ts_ver" ] || { echo "build: cannot read the tailscale.com version from go.mod" >&2; exit 1; }
{
    echo "# Generated by \`dotfiles stacks cxagents build\`. Do not edit."
    echo "go $(sed -n 's/^go //p' "${src}/go.mod")"
    echo "toolchain ${toolchain}"
    echo "tailscale.com ${ts_ver}"
    echo "builder ${builder}"
    echo "runtime ${runtime}"
    echo "binary sha256:${bin_sha} linux/arm64"
} > "$tmp/build.lock"
mv "$tmp/build.lock" "$lock"
echo "build: ${img} (binary sha256:${bin_sha})"
